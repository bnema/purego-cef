func TestEmitRaw(t *testing.T) {
	header := &model.Header{
		Path:         "cef_app_capi.h",
		Package:      "raw",
		RegisterName: "RegisterApp",
		Structs: []model.Struct{
			{
				CName:  "cef_app_t",
				GoName: "CEFAppT",
				Kind:   "handler",
				Fields: []model.Field{
					{
						CName:  "base",
						GoName: "Base",
						CType:  "cef_base_ref_counted_t",
						GoType: "CEFBaseRefCountedT",
					},
					{
						CName:      "get_browser_process_handler",
						GoName:     "GetBrowserProcessHandler",
						CType:      "void*",
						GoType:     "uintptr",
						IsFunction: true,
					},
				},
			},
		},
		Functions: []model.Function{
			{
				CName:        "cef_execute_process",
				GoName:       "CEFExecuteProcess",
				ReturnGoType: "int32",
				Params: []model.Param{
					{CName: "args", GoName: "Args", GoType: "unsafe.Pointer"},
				},
			},
		},
	}

	got, err := EmitRaw(header)
	if err != nil {
		t.Fatalf("EmitRaw() error: %v", err)
	}

	checks := []string{
		"// Code generated by cefgen. DO NOT EDIT.",
		"package raw",
		"type CEFAppT struct",
		"structs.HostLayout",
		"CallGetBrowserProcessHandler",
		"OverrideGetBrowserProcessHandler",
		"purego.SyscallN",
		"func RegisterApp(handle uintptr)",
		`purego.RegisterLibFunc(&CEFExecuteProcess, handle, "cef_execute_process")`,
		"var CEFExecuteProcess func(Args unsafe.Pointer) int32",
	}

	for _, want := range checks {
		if !strings.Contains(got, want) {
			t.Errorf("EmitRaw() output missing %q\n\nGot:\n%s", want, got)
		}
	}
}

